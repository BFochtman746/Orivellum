#!/usr/bin/env node
// Writes src/build-info.ts with the current git SHA and ISO timestamp.
// Runs automatically via the predev / prebuild npm lifecycle hook.

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

let sha = 'dev';
try {
  sha = execSync('git rev-parse --short HEAD', { encoding: 'utf8', stdio: ['pipe','pipe','pipe'] }).trim();
} catch {
  // not in a git repo or git unavailable — keep 'dev'
}

const time = new Date().toISOString();

const content = `// Auto-generated by scripts/generate-build-info.mjs — do not edit
export const BUILD_SHA = '${sha}';
export const BUILD_TIME = '${time}';
`;

writeFileSync(join(__dirname, '../src/build-info.ts'), content, 'utf8');
console.log(`[build-info] ${sha} @ ${time}`);
